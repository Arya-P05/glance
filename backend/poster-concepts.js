export function parseDirectorScene(text) {
  const cleaned = String(text || "").trim();
  const jsonText = cleaned.match(/\{[\s\S]*\}/)?.[0] || cleaned;
  const parsed = JSON.parse(jsonText);
  const required = ["subject", "action", "setting", "camera", "weather", "emotion"];
  for (const key of required) {
    if (!parsed[key] || typeof parsed[key] !== "string") {
      throw new Error(`Scene director JSON missing ${key}`);
    }
  }
  return {
    conceptId: String(parsed.conceptId || `director-${Date.now()}`),
    vibe: String(parsed.vibe || "candid moodboard moment"),
    subjectKind: parsed.subjectKind === "animal" ? "animal" : "person",
    subject: parsed.subject.trim(),
    action: parsed.action.trim(),
    setting: parsed.setting.trim(),
    camera: String(parsed.camera || "raw early-2000s digital camera photo").trim(),
    weather: parsed.weather.trim(),
    timeOfDay: String(parsed.timeOfDay || parsed.weather).trim(),
    prop: parsed.prop === "nothing" || !parsed.prop ? "nothing" : String(parsed.prop).trim(),
    cameraAngle: String(parsed.cameraAngle || parsed.composition || "subject close to the lens, low camera angle, open negative space above").trim(),
    composition: String(parsed.composition || parsed.cameraAngle || "subject close to the lens, low camera angle, open negative space above").trim(),
    colorDirection: String(parsed.colorDirection || "clean early-digital blue and green color").trim(),
    emotion: String(parsed.emotion || "gentle").trim(),
    copyFormula: String(parsed.copyFormula || "plain opener, then deadpan truth").trim(),
    source: "director",
  };
}
