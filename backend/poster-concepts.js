export function settingFamily(setting = "") {
  const s = String(setting).toLowerCase();
  if (/fireworks|night court|sparkler/.test(s)) return "fireworks-night";
  if (/desk|bedroom|gaming|monitor|wall|laundromat|porch|kitchen|diner|museum|dorm|arcade|bookstore|barbershop|noodle|apartment/.test(s)) return "indoor-wall";
  if (/bodega|corner store|bus shelter|subway|thrift|flea market/.test(s)) return "urban-street";
  if (/parking garage/.test(s)) return "urban-sky";
  if (/parking|rest stop|gas station|road|highway|fair/.test(s)) return "roadside";
  if (/beach|ocean|lake|dock|ferry|canoe|boat|water/.test(s)) return "water";
  if (/snow|winter|arctic|cabin/.test(s)) return "snow";
  if (/cockpit|fighter/.test(s)) return "cockpit";
  if (/mountain|overlook|desert|hill|field|grass|sunflower|farm|pasture|picnic|pine/.test(s)) return "outdoor-land";
  if (/fog|mist/.test(s)) return "fog";
  if (/balcony|rooftop|fire escape/.test(s)) return "urban-sky";
  if (/festival|street festival/.test(s)) return "festival";
  return "other";
}

export function sceneSignature(scene = {}) {
  const family = settingFamily(scene.setting);
  const subjectRoot = String(scene.subject || "")
    .toLowerCase()
    .replace(/^a\s+/, "")
    .split(/\s+/)[0];
  const actionKey = String(scene.action || "")
    .toLowerCase()
    .replace(/[^a-z0-9\s]/g, "")
    .split(/\s+/)
    .filter(Boolean)
    .slice(0, 4)
    .join("-");
  return `${family}|${actionKey}|${subjectRoot}`;
}

export function sceneDedupKeys(scene = {}) {
  const keys = new Set();
  if (scene.conceptId) keys.add(`concept:${scene.conceptId}`);
  keys.add(sceneSignature(scene));
  keys.add(`family:${settingFamily(scene.setting)}`);
  return keys;
}

export function isSceneBlocked(scene, avoidSignatures = new Set()) {
  for (const key of sceneDedupKeys(scene)) {
    if (avoidSignatures.has(key)) return true;
  }
  return false;
}

export function sampleArchetypesForDirector(count = 5, rng = Math.random) {
  const pool = [...POSTER_ARCHETYPES];
  const picked = [];
  while (picked.length < count && pool.length) {
    const idx = Math.floor(rng() * pool.length);
    picked.push(pool.splice(idx, 1)[0]);
  }
  return picked;
}

export function buildSceneDirectorPrompt({ avoidSignatures = new Set(), examples = sampleArchetypesForDirector() }) {
  const exampleBlock = examples
    .map(
      (a) =>
        `- ${a.vibe}: ${pickFrom(a.subjects)} ${a.action} | ${pickFrom(a.settings)} | camera: ${pickFrom(a.cameras)}`
    )
    .join("\n");

  const avoidList = [...avoidSignatures]
    .filter((k) => k.startsWith("family:") || k.startsWith("concept:"))
    .slice(0, 20)
    .map((k) => `- ${k.replace(/^(family|concept):/, "")}`)
    .join("\n");

  return `Invent ONE brand-new moodboard poster photo concept for a square Instagram lock-screen widget.

Style references (do NOT copy — match this level of specificity and vibe):
${exampleBlock}

Each concept must feel like:
- one specific camera-roll moment, not a stock photo category
- unexpected but visually coherent (wholesome, ironic, meme-worthy, documentary, or moody — not generic)
- subject large and low in frame with huge negative space above for text later
- raw early-2000s grainy digital photo energy

Banned overused ideas (do NOT use):
- fireworks, sparklers, outdoor basketball court at night
- generic "plain wall" unless sunlight or a prop makes it interesting
- parking lot unless tied to a specific road-trip or skate moment
${avoidList ? `\nRecently used — avoid similar:\n${avoidList}` : ""}

Return ONLY JSON with these exact fields:
{
  "conceptId": "short-kebab-id",
  "vibe": "3-6 word mood label",
  "subjectKind": "animal" or "person",
  "subject": "full subject phrase",
  "action": "pose/behavior only, no location words",
  "setting": "one specific place, richly described",
  "camera": "camera texture phrase",
  "weather": "light/weather phrase",
  "timeOfDay": "same as weather or time phrase",
  "prop": "nothing or one simple prop",
  "cameraAngle": "composition phrase",
  "composition": "same as cameraAngle",
  "colorDirection": "color palette phrase",
  "emotion": "one of: gentle, funny, momentum, self-worth, perspective",
  "copyFormula": "small phrase comma, then a bigger truth"
}`;
}

function pickFrom(items) {
  return items[Math.floor(Math.random() * items.length)];
}

export function parseDirectorScene(text) {
  const cleaned = String(text || "").trim();
  const jsonText = cleaned.match(/\{[\s\S]*\}/)?.[0] || cleaned;
  const parsed = JSON.parse(jsonText);
  const required = ["subject", "action", "setting", "camera", "weather", "emotion"];
  for (const key of required) {
    if (!parsed[key] || typeof parsed[key] !== "string") {
      throw new Error(`Scene director JSON missing ${key}`);
    }
  }
  return {
    conceptId: String(parsed.conceptId || `director-${Date.now()}`),
    vibe: String(parsed.vibe || "candid moodboard moment"),
    subjectKind: parsed.subjectKind === "animal" ? "animal" : "person",
    subject: parsed.subject.trim(),
    action: parsed.action.trim(),
    setting: parsed.setting.trim(),
    camera: String(parsed.camera || "raw early-2000s digital camera photo").trim(),
    weather: parsed.weather.trim(),
    timeOfDay: String(parsed.timeOfDay || parsed.weather).trim(),
    prop: parsed.prop === "nothing" || !parsed.prop ? "nothing" : String(parsed.prop).trim(),
    cameraAngle: String(parsed.cameraAngle || parsed.composition || "subject close to the lens, low camera angle, open negative space above").trim(),
    composition: String(parsed.composition || parsed.cameraAngle || "subject close to the lens, low camera angle, open negative space above").trim(),
    colorDirection: String(parsed.colorDirection || "clean early-digital blue and green color").trim(),
    emotion: String(parsed.emotion || "gentle").trim(),
    copyFormula: String(parsed.copyFormula || "small phrase comma, then a bigger truth").trim(),
    source: "director",
  };
}
