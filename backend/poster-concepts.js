export function settingFamily(setting = "") {
  const s = String(setting).toLowerCase();
  if (/fireworks|night court|sparkler/.test(s)) return "fireworks-night";
  if (/desk|bedroom|gaming|monitor|wall|laundromat|porch|kitchen|diner|museum|dorm|arcade|bookstore|barbershop|noodle|apartment|laundry room|hallway|convention|community gym|community hall|boxing gym|press room|red-carpet/.test(s)) return "indoor-wall";
  if (/bodega|corner store|bus shelter|subway|thrift|flea market|city street|tiny bar|london-style/.test(s)) return "urban-street";
  if (/parking garage/.test(s)) return "urban-sky";
  if (/parking|rest stop|gas station|road|highway|fair|warehouse street|underpass|hotel driveway|paddock|pit-lane/.test(s)) return "roadside";
  if (/beach|ocean|lake|dock|ferry|canoe|boat|water/.test(s)) return "water";
  if (/snow|winter|arctic|cabin/.test(s)) return "snow";
  if (/cockpit|fighter/.test(s)) return "cockpit";
  if (/mountain|overlook|desert|hill|field|grass|sunflower|farm|pasture|picnic|pine|canyon|cliff|tourist lookout|wildflower/.test(s)) return "outdoor-land";
  if (/fog|mist/.test(s)) return "fog";
  if (/balcony|rooftop|fire escape/.test(s)) return "urban-sky";
  if (/festival|street festival|amusement|roller coaster/.test(s)) return "festival";
  return "other";
}

export function sceneSignature(scene = {}) {
  const family = settingFamily(scene.setting);
  const subjectRoot = String(scene.subject || "")
    .toLowerCase()
    .replace(/^a\s+/, "")
    .split(/\s+/)[0];
  const actionKey = String(scene.action || "")
    .toLowerCase()
    .replace(/[^a-z0-9\s]/g, "")
    .split(/\s+/)
    .filter(Boolean)
    .slice(0, 4)
    .join("-");
  return `${family}|${actionKey}|${subjectRoot}`;
}

export function sceneDedupKeys(scene = {}) {
  const keys = new Set();
  if (scene.conceptId) keys.add(`concept:${scene.conceptId}`);
  keys.add(sceneSignature(scene));
  keys.add(`family:${settingFamily(scene.setting)}`);
  return keys;
}

export function isSceneBlocked(scene, avoidSignatures = new Set()) {
  for (const key of sceneDedupKeys(scene)) {
    if (avoidSignatures.has(key)) return true;
  }
  return false;
}

export function sampleArchetypesForDirector(count = 5, rng = Math.random) {
  const pool = [...POSTER_ARCHETYPES];
  const picked = [];
  while (picked.length < count && pool.length) {
    const idx = Math.floor(rng() * pool.length);
    picked.push(pool.splice(idx, 1)[0]);
  }
  return picked;
}

